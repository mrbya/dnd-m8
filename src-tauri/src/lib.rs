use std::error::Error;

use tauri::Manager;

/// App data bootstrap.
pub mod bootstrap;
/// App Tauri command definitions.
pub mod command;
/// Data transfer objects exposed through Tauri commands.
pub mod dto;
/// Error mapping for Tauri commands.
pub mod error;
/// Global app state.
pub mod state;

/// Builds and runs Tauri application.
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let result = tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .setup(|app| {
            let state =
                bootstrap::build_state().map_err(|error| -> Box<dyn Error> { Box::new(error) })?;

            app.manage(state);

            Ok(())
        })
        .invoke_handler(tauri::generate_handler![command::get_character])
        .run(tauri::generate_context!());

    if let Err(error) = result {
        eprintln!("error while running D&D Mate: {error}");
    }
}
